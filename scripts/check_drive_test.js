// The driving test date in the pass box (20261104h): asked once the foglio rosa dates are in, counted
// down, with day-before and day-of advice, then the outcome of each attempt (pass, fail, postponed).
// Run: node scripts/check_drive_test.js (UILANG=it-IT; SRC= another public_html).
const {JSDOM}=require(process.env.JSDOM||'/tmp/node_modules/jsdom'); const fs=require('fs');
const root=process.env.SRC||require('path').resolve(__dirname,'../public_html');
const LANG=process.env.UILANG||'en-US', IT=LANG.startsWith('it');
const key=n=>{const d=new Date(); d.setDate(d.getDate()+n); return d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0');};
let html=fs.readFileSync(root+'/index.html','utf8').replace(/<script[^>]*src="app\.js[^>]*><\/script>/,'');
const dom=new JSDOM(html,{url:'https://patente.physyapps.com/',runScripts:'dangerously',pretendToBeVisual:true});
const w=dom.window; Object.defineProperty(w.navigator,'language',{value:LANG}); Object.defineProperty(w.navigator,'languages',{value:[LANG]});
w.localStorage.setItem('patente_level','3');
w.localStorage.setItem('patente_exam_outcome',JSON.stringify([{d:key(-1),r:'pass'}]));
w.localStorage.setItem('patente_pass_celebrated','1');
w.localStorage.setItem('patente_foglio_rosa',JSON.stringify({iss:key(-40),exp:key(300)}));
w.fetch=async(u)=>{const p=root+'/'+String(u).replace(/^https:\/\/patente\.physyapps\.com\//,'').replace(/\?.*$/,'');return{ok:true,status:200,json:async()=>JSON.parse(fs.readFileSync(p,'utf8')),text:async()=>fs.readFileSync(p,'utf8')}};
w.scrollTo=()=>{}; w.Element.prototype.scrollTo=function(){}; w.Element.prototype.scrollIntoView=function(){}; w.alert=()=>{};
w.matchMedia=()=>({matches:false,addEventListener(){},addListener(){}});
w.speechSynthesis={getVoices:()=>[],cancel(){},speak(){}}; w.SpeechSynthesisUtterance=class extends w.EventTarget{};
const s=w.document.createElement('script'); s.textContent=fs.readFileSync(root+'/app.js','utf8'); w.document.body.appendChild(s);
let fails=0; const ok=(c,m)=>{console.log((c?'ok  ':'FAIL')+' '+m); if(!c)fails++;};
const $=id=>w.document.getElementById(id);
setTimeout(()=>{
  w.italianoComplete=()=>true; w.renderDashboard();
  const B=()=>$('exam-date-box'), D=()=>B().querySelector('.drive-test');
  const store=()=>JSON.parse(w.localStorage.getItem('patente_drive_test')||'null');
  const put=o=>{w.localStorage.setItem('patente_drive_test',JSON.stringify(o)); w.renderDashboard();};
  ok(!!D() && !!D().querySelector('input[data-dt=d]'),'with the foglio rosa dates in, the box asks for the driving test date');
  ok(!!B().querySelector('[data-row=valid]'),'the foglio rosa rows stay above it');
  D().querySelector('input[data-dt=d]').value=key(-3); D().querySelector('[data-ed=dtset]').click();
  ok(!store(),'a date in the past is refused');
  D().querySelector('input[data-dt=d]').value=key(301); D().querySelector('[data-ed=dtset]').click();
  ok(!store(),'a date after the foglio rosa expires is refused');
  D().querySelector('input[data-dt=d]').value=key(24); D().querySelector('[data-ed=dtset]').click();
  ok(store() && store().d===key(24),'a date in the window is stored');
  ok(/(in 24 days|tra 24 giorni)/.test(D().textContent) && !D().querySelector('input'),'the countdown: '+D().querySelector('strong').textContent);
  ok(!D().querySelector('.exam-date-wish') && !D().querySelector('[data-ed=dtpass]'),'far from the test: no wish and no outcome buttons');
  D().querySelector('[data-ed=dtpage]').click();
  ok($('dash-drivetest-box') && $('dash-drivetest-box').open,'the link opens the driving test page on the dashboard');
  ok(typeof w.buildProgressBundle().settings.driveTest==='string','the driving test travels with sync');
  put({d:key(1),a:[]});
  ok(/(tomorrow|domani)/.test(D().textContent) && !!D().querySelector('.exam-date-wish') && /(Sleep a full night|Dormi una notte piena)/.test(D().textContent) && /permesso di soggiorno/.test(D().textContent),'the day before: sleep, the residence permit and the wish');
  put({d:key(0),a:[]});
  ok(/(is today|oggi)/.test(D().querySelector('strong').textContent) && !!D().querySelector('[data-ed=dtpass]') && !!D().querySelector('[data-ed=dtfail]'),'the day itself offers the outcome');
  put({d:key(-1),a:[]});
  ok(/(How did your driving test|Com.+andato l.esame di guida)/.test(D().textContent) && !!D().querySelector('[data-ed=dtpost]'),'the day after asks how it went');
  D().querySelector('[data-ed=dtpost]').click();
  ok(!store() && !!D().querySelector('input[data-dt=d]'),'postponed: the date is cleared and asked again');
  put({d:key(-1),a:[]}); D().querySelector('[data-ed=dtfail]').click();
  let st=store();
  ok(st && !st.d && st.a.length===1 && st.a[0].r==='fail','a fail is recorded and the date cleared');
  ok(/(attempt 1 of 3|tentativo 1 di 3)/.test(D().textContent) && !!D().querySelector('input[data-dt=d]'),'after a fail: the attempt count, the next possible day and the date field');
  const mn=D().querySelector('input[data-dt=d]').min; const [y,m,d]=key(-1).split('-').map(Number); const nd=new Date(y,m,d);
  ok(mn===nd.getFullYear()+'-'+String(nd.getMonth()+1).padStart(2,'0')+'-'+String(nd.getDate()).padStart(2,'0'),'the next attempt is a month after the failed one: '+mn);
  D().querySelector('[data-ed=dtundo]').click();
  ok(store() && store().d===key(-1) && !store().a.length,'Change my answer restores the date and asks again');
  put({d:null,a:[{d:key(-100),r:'fail'},{d:key(-60),r:'fail'},{d:key(-5),r:'fail'}]});
  ok(/(No further attempt|non .+ possibile un altro tentativo)/.test(D().textContent) && !D().querySelector('input'),'three fails: no date field, ask the school');
  put({d:key(-1),a:[]}); D().querySelector('[data-ed=dtpass]').click();
  ok(/(passed the driving test|superato l.esame di guida)/.test(D().textContent) && /neopatentato/.test(D().textContent),'a pass congratulates and names the new-driver limits');
  ok(!B().querySelector('[data-row=valid]') && !B().querySelector('input'),'after the pass the foglio rosa rows and the date field are gone');
  ok(w.localStorage.getItem('patente_drive_celebrated')===key(-1),'the pass is celebrated once');
  D().querySelector('[data-ed=dtundo]').click();
  ok(store().d===key(-1) && !!B().querySelector('[data-row=valid]'),'undoing the pass brings the foglio rosa back');
  w.localStorage.removeItem('patente_foglio_rosa'); w.localStorage.removeItem('patente_drive_test'); w.renderDashboard();
  ok(!D(),'without the foglio rosa dates the driving test is not asked');
  console.log(fails?fails+' FAILED':'all passed'); process.exit(fails?1:0);
},1500);
